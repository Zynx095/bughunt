"""Movement Intelligence Engine for CrowdGuard VCIE.

Analyzes tracked pedestrian trajectories, computes velocity fields, detects opposing flows,
slow-moving queues, bottlenecks, and generates actionable human-review safety alerts.

Disclaimer: All movement vectors, bottlenecks, and flow metrics generated by this module
are indicators intended to support human supervisory review and situational awareness,
not definitive autonomous predictions of crowd catastrophes.
"""
from __future__ import annotations

import logging
import math
from typing import List, Optional, Tuple
import cv2
import numpy as np

from .calibration import CameraCalibrationEngine
from .schemas import (
    CongestionAlert,
    MovementVector,
    TrackedPerson,
    ZoneMetric,
)

logger = logging.getLogger(__name__)


class MovementIntelligenceEngine:
    """Extracts movement vectors, detects flow bottlenecks and opposing flows."""

    def __init__(
        self,
        calibration: CameraCalibrationEngine,
        bottleneck_speed_mps_threshold: float = 0.45,
        opposing_flow_angle_threshold_deg: float = 135.0,
        opposing_flow_distance_px: float = 55.0,
    ):
        self.calib = calibration
        self.bottleneck_speed_mps = bottleneck_speed_mps_threshold
        self.opposing_angle_threshold = opposing_flow_angle_threshold_deg
        self.opposing_distance_px = opposing_flow_distance_px

    def extract_movement_vectors(
        self,
        tracks: List[TrackedPerson],
        vector_scale: float = 1.2,
    ) -> List[MovementVector]:
        """Calculates instantaneous movement vectors suitable for top-down arrow rendering."""
        vectors: List[MovementVector] = []
        for trk in tracks:
            # Require minimum track history for reliable vector
            if len(trk.history) < 2:
                continue

            # Compute direction from smoothed history (last 5 points)
            pts = trk.history[-min(5, len(trk.history)):]
            dx = pts[-1].birdseye_x - pts[0].birdseye_x
            dy = pts[-1].birdseye_y - pts[0].birdseye_y
            dist = math.hypot(dx, dy)

            start_x, start_y = trk.birdseye_point
            if dist < 2.0:
                # Stationary or minimal movement
                end_x, end_y = start_x, start_y
                heading = trk.heading_deg
            else:
                heading = (math.degrees(math.atan2(dy, dx)) + 360.0) % 360.0
                # Scale vector arrow length proportional to speed
                arrow_len = max(12.0, min(50.0, trk.speed_mps * 18.0 * vector_scale))
                rad = math.radians(heading)
                end_x = start_x + arrow_len * math.cos(rad)
                end_y = start_y + arrow_len * math.sin(rad)

            # Check if person is in bottleneck / stagnation state
            risk_ind = None
            if trk.speed_mps < self.bottleneck_speed_mps:
                risk_ind = "stagnant"

            vectors.append(
                MovementVector(
                    track_id=trk.track_id,
                    start_x=round(start_x, 1),
                    start_y=round(start_y, 1),
                    end_x=round(end_x, 1),
                    end_y=round(end_y, 1),
                    speed_mps=round(trk.speed_mps, 2),
                    heading_deg=round(heading, 1),
                    risk_indicator=risk_ind,
                )
            )
        return vectors

    def analyze_congestion_and_alerts(
        self,
        tracks: List[TrackedPerson],
        zone_metrics: List[ZoneMetric],
        density_grid: np.ndarray,
        timestamp_s: float,
    ) -> List[CongestionAlert]:
        """Scans crowd patterns for safety alerts (bottlenecks, opposing flows, rapid accumulation)."""
        alerts: List[CongestionAlert] = []
        h, w = density_grid.shape[:2]

        # 1. Bottleneck Detection (High local density combined with severely reduced speed)
        for trk in tracks:
            bx, by = trk.birdseye_point
            ix, iy = int(round(bx)), int(round(by))
            if 0 <= ix < w and 0 <= iy < h:
                local_density = float(density_grid[iy, ix])
                if local_density >= 1.5 and trk.speed_mps < self.bottleneck_speed_mps:
                    # Found stagnant individual in dense cluster
                    alerts.append(
                        CongestionAlert(
                            id=f"alert-bneck-{trk.track_id}-{int(timestamp_s * 10)}",
                            timestamp_s=timestamp_s,
                            alert_type="bottleneck",
                            severity="high" if local_density > 2.5 else "moderate",
                            zone_id=trk.zone_id,
                            message=f"Bottleneck detected at ({ix}, {iy}): Density {local_density:.1f} p/m² with pedestrian speed dropped to {trk.speed_mps:.2f} m/s.",
                            location_birdseye=(round(bx, 1), round(by, 1)),
                            metrics={"local_density": round(local_density, 2), "speed_mps": round(trk.speed_mps, 2)},
                            recommendation="Inspect bottleneck constriction point; clear egress paths and adjust entry throttling.",
                        )
                    )
                    # Limit duplicate bottleneck alerts in same area
                    if len(alerts) >= 3:
                        break

        # 2. Opposing Flow Detection (Counterflow / Two streams colliding)
        opposing_pairs = self._detect_opposing_flows(tracks)
        for t1, t2, angle, dist_px in opposing_pairs[:2]:
            mid_x = (t1.birdseye_point[0] + t2.birdseye_point[0]) / 2.0
            mid_y = (t1.birdseye_point[1] + t2.birdseye_point[1]) / 2.0
            alerts.append(
                CongestionAlert(
                    id=f"alert-opp-{t1.track_id}-{t2.track_id}-{int(timestamp_s * 10)}",
                    timestamp_s=timestamp_s,
                    alert_type="opposing_flow",
                    severity="high" if (t1.speed_mps > 0.8 and t2.speed_mps > 0.8) else "moderate",
                    zone_id=t1.zone_id or t2.zone_id,
                    message=f"Counterflow detected: opposing streams colliding at {angle:.0f}° angle (separation: {dist_px:.1f} px).",
                    location_birdseye=(round(mid_x, 1), round(mid_y, 1)),
                    metrics={"angle_deg": round(angle, 1), "distance_px": round(dist_px, 1)},
                    recommendation="Deploy directional stanchions or marshals to segregate bidirectional traffic into distinct lanes.",
                )
            )

        # 3. Zone Overcapacity / Severe Density
        for zm in zone_metrics:
            if zm.density_per_sq_meter >= 3.0:
                alerts.append(
                    CongestionAlert(
                        id=f"alert-dens-{zm.zone_id}-{int(timestamp_s * 10)}",
                        timestamp_s=timestamp_s,
                        alert_type="severe_density",
                        severity="critical",
                        zone_id=zm.zone_id,
                        message=f"CRITICAL DENSITY in {zm.zone_name}: {zm.density_per_sq_meter:.2f} persons/m² exceeds safety envelope (>3.0 p/m²).",
                        location_birdseye=(float(w // 2), float(h // 2)),
                        metrics={"zone_density": zm.density_per_sq_meter, "population": zm.population, "occupancy_pct": zm.occupancy_pct},
                        recommendation="Immediate ingress hold required. Divert incoming attendees to secondary corridors.",
                    )
                )

        return alerts

    def _detect_opposing_flows(
        self,
        tracks: List[TrackedPerson],
    ) -> List[Tuple[TrackedPerson, TrackedPerson, float, float]]:
        """Finds pairs of tracks in close proximity with anti-parallel headings."""
        pairs = []
        n = len(tracks)
        for i in range(n):
            t1 = tracks[i]
            if t1.speed_mps < 0.2:
                continue
            for j in range(i + 1, n):
                t2 = tracks[j]
                if t2.speed_mps < 0.2:
                    continue

                dist = math.hypot(
                    t1.birdseye_point[0] - t2.birdseye_point[0],
                    t1.birdseye_point[1] - t2.birdseye_point[1],
                )
                if dist < self.opposing_distance_px:
                    # Calculate angle difference between headings
                    diff = abs(t1.heading_deg - t2.heading_deg)
                    if diff > 180.0:
                        diff = 360.0 - diff
                    if diff >= self.opposing_angle_threshold:
                        pairs.append((t1, t2, diff, dist))
        return pairs

    def draw_movement_overlay(
        self,
        birdseye_image: np.ndarray,
        vectors: List[MovementVector],
        draw_labels: bool = True,
    ) -> np.ndarray:
        """Renders movement direction arrows and velocity vectors on top-down image."""
        out = birdseye_image.copy()
        for v in vectors:
            p1 = (int(round(v.start_x)), int(round(v.start_y)))
            p2 = (int(round(v.end_x)), int(round(v.end_y)))

            # Pick color based on speed / stagnation
            if v.risk_indicator == "stagnant":
                arrow_color = (40, 40, 240)  # red for stagnation
            elif v.speed_mps > 1.4:
                arrow_color = (0, 230, 255)  # yellow/gold for brisk movement
            else:
                arrow_color = (50, 220, 100)  # green for standard pedestrian pace

            # Draw person position point
            cv2.circle(out, p1, 4, arrow_color, -1, cv2.LINE_AA)

            # Draw arrow if moving
            if math.hypot(p2[0] - p1[0], p2[1] - p1[1]) >= 4:
                cv2.arrowedLine(out, p1, p2, arrow_color, 2, tipLength=0.35, line_type=cv2.LINE_AA)

            if draw_labels and v.speed_mps > 0.15:
                label = f"{v.speed_mps:.1f}m/s"
                cv2.putText(out, label, (p1[0] + 6, p1[1] - 4),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.35, (220, 220, 240), 1, cv2.LINE_AA)

        return out
