import { AlertTriangle, Bot, CheckCircle2, CircleSlash, Cpu, Loader2, Sparkles, XCircle } from 'lucide-react'

import { fmtMs, fmtValue } from '../lib/format'
import type { Narrative, Presentation, RunRecord, RunStep, StepInfo } from '../lib/types'
import { ChartCard } from './charts'
import { DataTable } from './table'
import { Badge, Card, Disclosure, JsonView, Stat } from './ui'
import { cx } from '../lib/cx'

export function NarrativeCard({ narrative, title = 'Explanation' }: { narrative: Narrative; title?: string }) {
  const llm = !narrative.fallback && narrative.source !== 'unknown'
  return (
    <Card title={title} actions={llm ? (
      <Badge tone="info" title="Generated by a language model from the structured results above"><Sparkles className="size-3" aria-hidden />{narrative.source}{narrative.model ? ` · ${narrative.model}` : ''}</Badge>
    ) : (
      <Badge tone="neutral" title="No LLM was used: deterministic local method (template, extractive or rule-based)"><Cpu className="size-3" aria-hidden />local fallback (no LLM)</Badge>
    )}>
      <p className="whitespace-pre-line text-sm leading-relaxed text-ink">{narrative.text}</p>
      {llm && <p className="mt-2 flex items-center gap-1 text-[11px] text-muted"><Bot className="size-3" aria-hidden />Advisory text only — it does not change any decision above.</p>}
    </Card>
  )
}

export function PresentationView({ p }: { p: Presentation }) {
  return (
    <div className="space-y-4">
      <div className="rounded-xl border border-[var(--accent)]/30 bg-[var(--accent)]/[0.07] px-4 py-3">
        <p className="text-[11px] font-semibold uppercase tracking-wide text-muted">Result</p>
        <p className="mt-0.5 text-base font-semibold text-ink">{p.headline}</p>
      </div>
      {p.metrics.length > 0 && (
        <div className="grid grid-cols-2 gap-3 md:grid-cols-3 xl:grid-cols-5">
          {p.metrics.map((m) => <Stat key={m.label} label={m.label} value={fmtValue(m.value)} hint={m.hint ?? undefined} tone={m.tone} />)}
        </div>
      )}
      {p.narrative && <NarrativeCard narrative={p.narrative} />}
      {p.charts.length > 0 && (
        <div className={cx('grid gap-4', p.charts.length > 1 && 'xl:grid-cols-2')}>
          {p.charts.map((c) => <ChartCard key={c.title} spec={c} />)}
        </div>
      )}
      {p.tables.filter((t) => t.rows.length).map((t) => (
        <Card key={t.title} title={t.title} subtitle={`${t.rows.length} row${t.rows.length === 1 ? '' : 's'}`}>
          <div className="max-h-[28rem] overflow-auto"><DataTable columns={t.columns} rows={t.rows} /></div>
        </Card>
      ))}
      {p.artifacts && Object.keys(p.artifacts).length > 0 && (
        <Disclosure summary={<span className="font-medium">Cryptographic artifacts <span className="text-muted">({Object.keys(p.artifacts).join(', ')})</span></span>}>
          <JsonView value={p.artifacts} />
        </Disclosure>
      )}
      {p.notes.length > 0 && (
        <ul className="space-y-1 rounded-xl border border-line bg-surface-2 px-4 py-3 text-xs text-ink-2">
          {p.notes.map((n) => <li key={n} className="flex gap-2"><span aria-hidden>•</span>{n}</li>)}
        </ul>
      )}
    </div>
  )
}

const STEP_ICON = {
  completed: <CheckCircle2 className="size-4 text-good-ink" aria-label="completed" />,
  failed: <XCircle className="size-4 text-critical-ink" aria-label="failed" />,
  skipped: <CircleSlash className="size-4 text-muted" aria-label="skipped" />,
  running: <Loader2 className="size-4 animate-spin text-muted" aria-label="running" />,
}

/** Pipeline steps: declared steps before a run, real per-step status after. Nothing is animated without a real state. */
export function StepList({ steps, run, running }: { steps: StepInfo[]; run?: RunRecord | null; running?: boolean }) {
  const byId = new Map<string, RunStep>((run?.steps ?? []).map((s) => [s.id, s]))
  return (
    <ol className="space-y-1.5">
      {steps.map((s, i) => {
        const r = byId.get(s.id)
        const notReached = run && !r
        return (
          <li key={s.id} className={cx('rounded-lg border border-line px-3 py-2', notReached && 'opacity-50')}>
            <div className="flex items-start gap-2">
              <span className="mt-0.5 shrink-0">
                {running ? STEP_ICON.running : r ? STEP_ICON[r.status] : <span className="tabular inline-flex size-4 items-center justify-center rounded-full bg-surface-2 text-[10px] font-semibold text-muted">{i + 1}</span>}
              </span>
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-baseline justify-between gap-x-2">
                  <p className="text-sm font-medium text-ink">{s.title}{s.optional && <span className="ml-1 text-[11px] font-normal text-muted">(optional)</span>}</p>
                  {r && <span className="tabular text-[11px] text-muted">{fmtMs(r.execution_time_ms)}{r.items > 1 ? ` · ${r.items}×` : ''}</span>}
                </div>
                <p className="font-mono text-[11px] text-muted">{s.engine}.{s.operation}{s.foreach ? ' (per item)' : ''}</p>
                {s.why && !r && <p className="mt-0.5 text-xs text-ink-2">{s.why}</p>}
                {r?.error && <p className="mt-1 text-xs text-critical-ink">{r.error}</p>}
                {r?.warnings?.map((w) => (
                  <p key={w} className="mt-1 flex items-start gap-1 text-[11px] text-warn-ink"><AlertTriangle className="mt-px size-3 shrink-0" aria-hidden />{w}</p>
                ))}
              </div>
            </div>
          </li>
        )
      })}
    </ol>
  )
}

export function StepOutputs({ run }: { run: RunRecord }) {
  return (
    <div className="space-y-2">
      {run.steps.map((s) => (
        <Disclosure key={s.id} summary={
          <span className="flex flex-wrap items-center gap-2">
            {STEP_ICON[s.status]}<span className="font-medium">{s.title}</span>
            <span className="font-mono text-[11px] text-muted">{s.engine}.{s.operation}</span>
            {s.confidence !== undefined && s.confidence !== null && <Badge tone="neutral">confidence {s.confidence}</Badge>}
            {typeof s.metadata?.provider === 'string' && <Badge tone={s.metadata.fallback ? 'neutral' : 'info'}>{s.metadata.provider as string}</Badge>}
          </span>
        }>
          <JsonView value={{ result: s.result, metadata: s.metadata, warnings: s.warnings, error: s.error }} maxHeight={420} />
        </Disclosure>
      ))}
    </div>
  )
}
